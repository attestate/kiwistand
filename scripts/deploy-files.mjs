// Decides which files a deploy ships to the server and ships them. Used by
// `npm run rsync` (and so `npm run deploy`) and by .github/workflows/deploy.yml,
// so a deploy from a laptop sends exactly what CI sends.
//
// The list is every file git tracks (`git ls-files`) plus the outputs of
// `npm run build` and `npm run build:docs`, minus a few tracked paths
// production doesn't need (EXCLUDED). Untracked and gitignored files (.env,
// .keys.json, keys, editor and agent histories, ...) are never in it. rsync
// runs with --files-from and without --delete, so server-only files (.env,
// .keys.json, data/, cache/, ...) are never touched.
//
// As a second line of defense the script refuses to run when the list contains
// anything that looks like a secret or a server-only path (FORBIDDEN), e.g.
// because someone committed a .env.
//
//   node scripts/deploy-files.mjs list            prints the list (dry run)
//   node scripts/deploy-files.mjs rsync <dest>    ships it to <dest>
//
// The ssh key comes from ~/.ssh/config or the ssh agent (CI writes a config).
import { execFileSync, spawnSync } from "child_process";
import { existsSync, lstatSync, readdirSync, writeFileSync, mkdtempSync, rmSync } from "fs";
import { tmpdir } from "os";
import path from "path";
import { fileURLToPath } from "url";

// Generated by `npm run build` and gitignored, but production serves them.
// src/http.mjs and src/views/components/head.mjs read manifest.json, the
// pages link news.min.css/pages.min.css, and assets/ holds the vite bundles.
export const BUILD_FILES = [
  "src/public/manifest.json",
  "src/public/.vite/manifest.json",
  "src/public/news.min.css",
  "src/public/pages.min.css",
];
export const BUILD_DIRS = ["src/public/assets"];
// The docs site, built by `npm run build:docs` (gitignored) and served at
// /docs by src/docs.mjs. Only this output ships, not docs/'s sources.
export const DOCS_BUILD_DIR = "docs/dist/public";

// Tracked, but not needed on the server (the old rsync excluded them too).
// .env-copy is the env template; it would trip the .env* guard below.
// docs/ is the docs' sources; their build is in buildOutputs().
export const EXCLUDED = [".claude/", "docs/", "src/iOS/", ".env-copy"];

// Never ship these. Matched against each file's basename...
export const FORBIDDEN_NAMES = [
  { pattern: /^\.env/, label: ".env*" },
  { pattern: /^\.keys\.json$/, label: ".keys.json" },
  { pattern: /\.pem$/, label: "*.pem" },
  { pattern: /\.key$/, label: "*.key" },
  { pattern: /\.p12$/, label: "*.p12" },
  { pattern: /^mcp\.config\.json$/, label: "mcp.config.json" },
  { pattern: /^\.aider/, label: ".aider*" },
  // ssh keys (id_rsa, id_ed25519, id_deploy, *.pub), but not test/id_test.mjs
  { pattern: /^id_[A-Za-z0-9_-]+(\.pub)?$/, label: "id_*" },
  { pattern: /^\.deployed-lock\.sha256$/, label: ".deployed-lock.sha256" },
];
// ...and these against its path: directories only the server has.
export const FORBIDDEN_DIRS = [
  "node_modules/",
  "data/",
  "cache/",
  "anon/",
  "anonlocal/",
  "bootstrap/",
  "certificates/",
  "logs/",
];

function walk(root, dir) {
  const abs = path.join(root, dir);
  if (!existsSync(abs)) return [];
  const out = [];
  for (const entry of readdirSync(abs, { withFileTypes: true })) {
    const rel = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(root, rel));
    else out.push(rel);
  }
  return out;
}

// Throws when the build outputs are missing: deploying without them would
// serve pages whose scripts and styles 404, or no docs at /docs.
export function buildOutputs(root) {
  const missing = BUILD_FILES.filter((f) => !existsSync(path.join(root, f)));
  const assets = BUILD_DIRS.flatMap((d) => walk(root, d));
  if (missing.length || assets.length === 0) {
    throw new Error(
      `Build outputs missing (${[...missing, ...(assets.length ? [] : BUILD_DIRS)].join(", ")}). Run \`npm run build\` first.`,
    );
  }
  const docs = walk(root, DOCS_BUILD_DIR);
  if (!docs.includes(`${DOCS_BUILD_DIR}/index.html`)) {
    throw new Error(`Docs build missing (${DOCS_BUILD_DIR}). Run \`npm run build:docs\` first.`);
  }
  return [...BUILD_FILES, ...assets, ...docs];
}

export function trackedFiles(root) {
  const out = execFileSync("git", ["-C", root, "ls-files", "-z", "--cached"], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return out.split("\0").filter(Boolean);
}

export function isExcluded(file) {
  return EXCLUDED.some((e) => (e.endsWith("/") ? file.startsWith(e) : file === e));
}

// Returns [{ file, reason }] for every entry that must not be shipped.
export function findForbidden(files) {
  const hits = [];
  for (const file of files) {
    const base = path.posix.basename(file);
    const name = FORBIDDEN_NAMES.find(({ pattern }) => pattern.test(base));
    if (name) {
      hits.push({ file, reason: name.label });
      continue;
    }
    const dir = FORBIDDEN_DIRS.find((d) => file.startsWith(d));
    if (dir) hits.push({ file, reason: dir });
  }
  return hits;
}

// The sorted list of paths (relative to root) a deploy ships. Throws if the
// guard trips or the build outputs are missing.
export function deployFiles(root) {
  const files = new Set();
  for (const file of trackedFiles(root)) {
    if (isExcluded(file)) continue;
    // A tracked file deleted in the working tree: rsync would fail on it.
    try {
      lstatSync(path.join(root, file));
    } catch {
      continue;
    }
    files.add(file);
  }
  for (const file of buildOutputs(root)) files.add(file);
  const list = [...files].sort();

  const forbidden = findForbidden(list);
  if (forbidden.length) {
    const lines = forbidden.map(({ file, reason }) => `  ${file}  (matches ${reason})`);
    throw new Error(
      `Refusing to deploy: the file list contains files that must never be shipped:\n${lines.join("\n")}`,
    );
  }
  return list;
}

function summary(list) {
  const top = {};
  for (const file of list) {
    const key = file.includes("/") ? file.split("/")[0] + "/" : file;
    top[key] = (top[key] || 0) + 1;
  }
  return { count: list.length, top };
}

function main(argv) {
  const root = execFileSync("git", ["rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();
  const [command, dest] = argv;

  if (command === "list") {
    const list = deployFiles(root);
    process.stdout.write(list.join("\n") + "\n");
    const { count, top } = summary(list);
    console.error(`${count} files`);
    for (const [k, n] of Object.entries(top).sort()) console.error(`  ${String(n).padStart(5)}  ${k}`);
    return 0;
  }

  if (command === "rsync" && dest) {
    const list = deployFiles(root);
    const dirty = execFileSync("git", ["-C", root, "status", "--porcelain", "--untracked-files=no"], {
      encoding: "utf8",
    }).trimEnd();
    if (dirty) console.error(`Warning: shipping uncommitted changes to tracked files:\n${dirty}`);

    const tmp = mkdtempSync(path.join(tmpdir(), "deploy-files-"));
    const listFile = path.join(tmp, "files");
    try {
      writeFileSync(listFile, list.join("\0") + "\0");
      console.error(`Shipping ${list.length} files to ${dest}`);
      // No --delete: files only the server has stay untouched.
      const res = spawnSync(
        "rsync",
        ["-az", "--stats", "--from0", `--files-from=${listFile}`, "./", dest],
        { cwd: root, stdio: "inherit" },
      );
      if (res.error) throw res.error;
      return res.status ?? 1;
    } finally {
      rmSync(tmp, { recursive: true, force: true });
    }
  }

  console.error("usage: node scripts/deploy-files.mjs list | rsync <user@host:dir>");
  return 2;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exit(main(process.argv.slice(2)));
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
